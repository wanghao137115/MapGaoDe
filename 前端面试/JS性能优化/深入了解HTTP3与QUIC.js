// 为什么需要HTTP3
// 1. 更快的连接建立
// 2. 更好的拥塞控制
// 3. 更低的延迟
// 4. 更好的安全性

// HTTP2虽然解决了HTTP1.1的一些问题，但仍然存在一些限制，例如：
// 1. 头部压缩仍然存在一定开销
// 2. 仍然依赖于TCP协议
// 3. 服务器推送功能不够灵活

// QUIC基于UDP协议，解决了TCP的一些固有问题，例如：
// 1. 减少连接建立时间
// 2. 提高拥塞控制效率
// 3. 支持多路复用

// QUIC的核心机制：
// 1. 连接建立和加密协商合并为一个步骤
// 2. 使用0-RTT和1-RTT技术减少延迟
// 3. 基于流的多路复用
// 4.每个请求都有独立的Stream ID，避免了队头阻塞问题
// 5.一个Stream丢包不会影响其他Stream