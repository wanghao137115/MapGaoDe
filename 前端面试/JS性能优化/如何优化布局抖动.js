// 什么是布局抖动
// 布局抖动是指在页面渲染过程中，由于元素的尺寸、位置等属性发生变化，导致浏览器需要重新计算布局，从而引发一系列的重排和重绘操作。这种情况通常会影响用户体验，导致页面闪烁、卡顿等问题。
// 理想情况：
// 在理想情况下，页面的布局和渲染应该是稳定的，不会因为微小的变化而导致大规模的重排和重绘。可以通过以下方式来优化布局抖动：
// 1. 减少DOM元素的数量和复杂度，避免不必要的嵌套和层级。
// 2. 使用CSS3的transform和opacity等属性进行动画，避免触发重排。
// 3. 合并多个DOM操作，减少重排的次数。
// 4.希望一次性完成布局和绘制。

// 强制同步布局如何触发
// 1. 读取元素的布局信息（如offsetWidth、offsetHeight等）会导致浏览器强制同步布局。
// 2. 使用getComputedStyle()获取元素的计算样式也会触发布局。
// 3. 在DOM操作后，使用requestAnimationFrame()可以将布局和绘制合并到一次渲染中。

// 避免的方法有
// 1. 避免频繁读取布局信息，尽量将读写操作分开进行。
// 2. 避免在动画过程中触发重排，使用transform和opacity等属性进行动画。
// 3. 避免在短时间内多次修改DOM，尽量合并操作。
// 4. 批量更新DOM，使用document.createDocumentFragment()或将元素隐藏后再进行操作。
// 5. 使用requestAnimationFrame()将多次DOM操作合并到一次渲染中。
