// watch和watchEffect区别
// 1. watch是侦听器，用于监听数据的变化，执行异步或开销较大的操作；watchEffect是响应式的副作用函数，用于自动追踪依赖，简化代码逻辑。
// 2. watch可以监听多个数据源，watchEffect只能监听当前作用域内的响应式数据。
// 3. watch的回调函数可以是异步的，watchEffect的回调函数必须是同步的。
// 4. watch的使用场景：需要在数据变化时执行副作用操作；watchEffect的使用场景：需要根据其他数据计算得出一个新值。

// watchEffect立即执行一个函数，当依赖的响应式数据发生变化时，会重新执行该函数。
// watch是懒执行的，只有在被监听的数据变化时才会执行回调函数。