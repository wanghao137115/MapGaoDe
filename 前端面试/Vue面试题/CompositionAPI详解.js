// ref介绍：ref是Vue 3中用于创建响应式引用的API。它可以用于基本数据类型和对象类型，能够自动追踪依赖并在值变化时触发视图更新。使用ref时，需要通过.value来访问和修改其值。
// reactive介绍：reactive是Vue 3中用于创建响应式对象的API。它可以将一个普通的JavaScript对象转换为响应式对象，使得当对象的属性发生变化时，视图能够自动更新。使用reactive创建的对象不需要通过.value来访问和修改属性，可以直接使用点语法进行操作。
// 为什么reactive不需要value
// 因为reactive是通过代理（Proxy）实现的，它可以直接监听对象属性的变化，而ref是通过包装一个值来实现的，需要通过.value来访问和修改。

// computed介绍：computed是Vue 3中用于创建计算属性的API。它可以根据依赖的响应式数据自动计算并缓存结果，当依赖的数据发生变化时，computed会重新计算并更新视图。使用computed时，不需要手动管理依赖，Vue会自动追踪。
// watch介绍：watch是Vue 3中用于监听响应式数据变化的API。它可以监听一个或多个响应式数据，当这些数据发生变化时，执行一个回调函数。watch适用于需要在数据变化时执行副作用操作的场景，例如发起网络请求或更新其他非响应式数据。