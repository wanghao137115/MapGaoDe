// 列表key的重要性
// 1. 提高渲染性能：通过唯一标识，Vue可以更精确地判断哪些节点需要更新，避免不必要的DOM操作。
// 2. 保持组件状态：在列表项的增删改操作中，key可以帮助Vue保持每个组件实例的状态，避免状态混乱。
// 3. 便于调试：使用key可以让开发者更容易地追踪和定位问题，提升调试效率。

// v-bind和v-model区别
// 1. v-bind用于动态绑定属性，而v-model用于双向数据绑定。
// 2. v-bind可以绑定任意属性，而v-model主要用于表单元素的value属性。
// 3. v-bind是单向数据流，而v-model是双向数据流。