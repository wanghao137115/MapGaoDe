// Vue组件化的理解
// 1. 组件化是将一个复杂的UI拆分成多个独立、可复用的组件，每个组件负责自己的渲染和逻辑。
// 2. 组件之间通过props和事件进行通信，父组件可以通过props向子组件传递数据，子组件通过事件向父组件发送消息。
// 3. 组件化可以提高代码的可维护性和可读性，降低耦合度，方便团队协作。
// 4. Vue的组件化实现：通过Vue.extend()方法定义组件，使用Vue.component()注册全局组件，使用组件标签在模板中引用组件。


