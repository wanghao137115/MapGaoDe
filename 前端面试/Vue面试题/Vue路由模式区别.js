// vue-router三种模式区别和作用
// 1. hash模式：通过URL的hash部分来模拟不同的页面，适合简单的应用，兼容性好，但不支持SEO。
// 2. history模式：利用HTML5的History API实现，支持后端路由，适合复杂应用，支持SEO，但需要后端配合。
// 3. abstract模式：用于非浏览器环境，如测试环境，所有的导航都是通过JavaScript控制，不会改变URL。

// 为什么hash不支持SEO？
// 因为hash模式的路由信息存储在URL的hash部分，hash部分不会被发送到服务器，因此搜索引擎无法索引这些内容。

// 为什么history模式需要后端配合？
// 因为history模式下，路由的变化会直接反映在URL上，当用户刷新页面或直接访问某个URL时，浏览器会向服务器发送请求，服务器需要根据请求的URL返回对应的页面内容。如果后端没有相应的路由配置，用户将无法访问到正确的页面。