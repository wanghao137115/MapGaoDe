// v-if和v-show的区别
// 1. v-if是条件渲染，只有在条件为真时才会渲染该元素；v-show是显示隐藏，始终渲染该元素，只是通过CSS控制其显示与隐藏。
// 2. v-if会销毁和重建DOM元素，v-show只会切换元素的display属性。
// 3. v-if适合用于切换较复杂的结构，v-show适合用于切换简单的显示状态。

// 哪个优先级高: vue3中 v-if > v-show 为什么：
// 因为v-if会销毁和重建DOM元素，而v-show只是切换元素的display属性，所以在需要频繁切换显示状态的情况下，v-show的性能更好；而在需要条件渲染复杂结构的情况下，v-if更为合适。

// 为什么不能嵌套v-if和v-show
// 因为v-if和v-show都是基于DOM的渲染机制，嵌套使用会导致渲染逻辑混乱，影响性能和可读性。建议使用v-if和v-show的组合来实现复杂的显示逻辑。