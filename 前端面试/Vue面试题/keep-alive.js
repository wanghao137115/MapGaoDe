// keep-alive 有三个属性 include、exclude 和 max 分别作用为 include 用于缓存指定的组件，exclude 用于排除指定的组件，max 用于限制缓存的组件数量。
// 1. 用于缓存组件状态，避免不必要的重新渲染。
// 2. 适用于需要保持用户输入或滚动位置的场景。
// 3. 可以与路由懒加载结合使用，提升应用性能。

// 使用场景:
// 1. 表单输入：用户在表单中输入数据时，切换组件后返回，输入内容仍然保留。
// 2. 滚动位置：用户在页面中滚动时，切换组件后返回，滚动位置仍然保留。
// 3. 路由懒加载：结合路由懒加载使用，提升应用性能，减少不必要的请求和渲染。
// 4. 动态组件：在动态组件切换时，保持组件状态，避免不必要的重新渲染。